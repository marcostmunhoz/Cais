// Grid edits: column metadata from the server, EXTRA from introspection, and UPDATEs generated by the grid
// that write back exactly what the person typed, whatever the sql_mode.

const dialect = getDialect('mysql');
let admin: mysql.Connection;
const opened: DbSession[] = [];

async function open(): Promise<DbSession> {
  const s = await mysqlDriver.open(params());
  opened.push(s);
  await s.applyMode('autocommit');
  return s;
}

beforeAll(async () => {
  admin = await observer();
  await admin.query(
    `CREATE TABLE grid_people (
       id INT PRIMARY KEY AUTO_INCREMENT,
       name VARCHAR(50) NOT NULL,
       upper_name VARCHAR(50) AS (UPPER(name)) VIRTUAL,
       name_len INT AS (CHAR_LENGTH(name)) STORED,
       changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
     )`,
  );
  await admin.query("INSERT INTO grid_people (name) VALUES ('Ana'), ('Bia')");
  await admin.query('CREATE TABLE grid_other (id INT PRIMARY KEY, name VARCHAR(50))');
  await admin.query("INSERT INTO grid_other VALUES (10, 'Zé')");
  await admin.query('CREATE VIEW grid_people_v AS SELECT id, name FROM grid_people');
  await admin.query(
    `CREATE TABLE grid_kinds (
       id BIGINT UNSIGNED PRIMARY KEY, s VARCHAR(200), t TEXT, ch CHAR(5), d DECIMAL(20,6), b BIGINT, dt DATETIME(6),
       j JSON, e ENUM('a','b','c d'), st SET('x','y'), bt BIT(10), vb VARBINARY(32), y YEAR, f DOUBLE
     )`,
  );
});

afterAll(async () => {
  await Promise.all(opened.map((s) => s.close().catch(() => undefined)));
  await admin?.query('DROP VIEW IF EXISTS grid_people_v');
  await admin?.query('DROP TABLE IF EXISTS grid_people, grid_other, grid_kinds');
  await admin?.end();
});

const schema = (): Promise<SchemaTree> => mysqlDriver.introspect(params());
/** What the SessionManager adds to a driver result: the classification of the statement. */
async function exec(s: DbSession, sql: string): Promise<StatementResult> {
  const c = dialect.classify(sql);
  return { ...(await s.execute(sql, { maxRows: 10 })), kind: c.kind, verb: c.verb };
}
const why = (r: StatementResult, tree: SchemaTree): string => {
  const e = gridEditability(r, tree, dialect.valueKind);
  return e.editable ? 'editable' : render(e.reason);
};

describe('column metadata (source, key flags)', () => {
  it('names the source table and column under aliases, and nothing for expressions', async () => {
    const s = await open();
    const db = fixture().database;
    const r = await exec(s, 'SELECT p.id AS pid, p.name, UPPER(p.name) AS up, 1 + 1 AS two FROM grid_people p ORDER BY p.id');
    expect(r.error).toBeUndefined();
    expect(r.columns![0]).toEqual({
      name: 'pid', type: 'int', source: { database: db, table: 'grid_people', column: 'id', alias: 'p' },
      primaryKeyPart: true, nullable: false, autoIncrement: true,
    });
    expect(r.columns![1]).toMatchObject({ name: 'name', source: { table: 'grid_people', column: 'name', alias: 'p' }, primaryKeyPart: false, nullable: false });
    expect(r.columns![2]).toEqual({ name: 'up', type: 'varchar' });
    expect(r.columns![3]).toEqual({ name: 'two', type: 'bigint' });
    expect(why(r, await schema())).toBe('editable');
  });

  it('a join, a self-join, a view, a UNION and expressions only are not editable', async () => {
    const s = await open();
    const tree = await schema();
    const join = await exec(s, 'SELECT p.id, p.name, o.id AS oid FROM grid_people p JOIN grid_other o ON o.id > p.id');
    expect(why(join, tree)).toMatch(/^Edição na grade só para resultado de uma tabela \(este vem de .*grid_people \(p\), .*grid_other \(o\)\)\.$/);
    const self = await exec(s, 'SELECT a.id, b.id AS bid FROM grid_people a JOIN grid_people b ON b.id = a.id');
    expect(why(self, tree)).toMatch(/grid_people \(a\), .*grid_people \(b\)/);
    const view = await exec(s, 'SELECT id, name FROM grid_people_v');
    expect(view.columns![0]!.source).toMatchObject({ table: 'grid_people_v', column: 'id' });
    expect(why(view, tree)).toMatch(/grid_people_v é uma view/);
    const union = await exec(s, 'SELECT id, name FROM grid_people UNION ALL SELECT id, name FROM grid_other');
    expect(union.columns!.every((c) => c.source === undefined)).toBe(true);
    expect(why(union, tree)).toMatch(/não vêm de uma tabela/);
    const expr = await exec(s, "SELECT 1 AS id, 'x' AS name");
    expect(why(expr, tree)).toMatch(/não vêm de uma tabela/);
    const noKey = await exec(s, 'SELECT name FROM grid_people');
    expect(why(noKey, tree)).toBe('Edição na grade só para resultado de uma tabela com a chave primária inteira (falta: id).');
  });
});

describe('introspection: EXTRA', () => {
  it('marks generated columns and ON UPDATE', async () => {
    const tree = await schema();
    const table = tree.databases[0]!.tables.find((t) => t.name === 'grid_people')!;
    const col = (n: string) => table.columns.find((c) => c.name === n)!;
    expect(col('id')).toEqual({ name: 'id', type: 'int', nullable: false, key: 'PRI' });
    expect(col('upper_name').generated).toBe('virtual');
    expect(col('name_len').generated).toBe('stored');
    expect(col('changed_at').onUpdate).toBe(true);
    expect(col('changed_at').generated).toBeUndefined();

    const s = await open();
    const r = await exec(s, 'SELECT * FROM grid_people');
    const e = gridEditability(r, tree, dialect.valueKind);
    expect(e.editable).toBe(true);
    if (!e.editable) return;
    expect(e.columns.map((c) => c.editable)).toEqual([true, true, false, false, true]);
  });
});

/** Every tricky value the grid must write back exactly. */
const VALUES: Record<string, CellValue> = {
  s: "it's \\ \\' \"q\" `b` ; /*! x */ -- y # z 😀 ‮ ção",
  t: "line1\nline2\r\n\ttab \u0000 nul \\n not a newline ''",
  ch: "a'b",
  d: '-12345678901234.123456',
  b: '-9223372036854775808',
  dt: '2026-11-12 10:20:30.123456',
  j: '{"k": "a\\"b\\\\c", "n": [1, 2.5, null], "u": "ção"}',
  e: 'c d',
  st: 'x,y',
  bt: { kind: 'binary', hex: '0201', length: 2 },
  vb: { kind: 'binary', hex: '00ff5c2722', length: 5 },
  y: 2026,
  f: 1.5e-7,
};

describe.each([
  ['the default sql_mode', ''],
  ['NO_BACKSLASH_ESCAPES', "SET SESSION sql_mode = CONCAT(@@sql_mode, ',NO_BACKSLASH_ESCAPES')"],
])('applying a generated UPDATE under %s', (_label, setup) => {
  it('round-trips every value exactly', async () => {
    const id = setup ? '18446744073709551615' : '9007199254740993';
    await admin.query('DELETE FROM grid_kinds WHERE id = ?', [id]);
    await admin.query(`INSERT INTO grid_kinds (id, s) VALUES (${id}, 'old')`);
    const s = await open();
    if (setup) expect((await s.execute(setup, { maxRows: 1 })).error).toBeUndefined();

    const read = `SELECT * FROM grid_kinds WHERE id = ${id}`;
    const before = await exec(s, read);
    const target = gridEditability(before, await schema(), dialect.valueKind) as EditTarget;
    expect(target.editable).toBe(true);
    const names = before.columns!.map((c) => c.name);
    const cells: PendingCells = { 0: {} };
    for (const [name, value] of Object.entries(VALUES)) cells[0]![names.indexOf(name)] = value;

    const [update] = buildGridUpdates(dialect, target, before.rows!, cells);
    expect(update!.sql).toContain(`WHERE \`id\` = ${id}`);
    const done = await s.execute(update!.sql, { maxRows: 1 });
    expect(done.error).toBeUndefined();
    expect(done.affectedRows).toBe(1);
    expect(done.warnings).toBeUndefined();

    const after = await exec(s, read);
    const row = after.rows![0]!;
    const got = (name: string) => row[names.indexOf(name)];
    for (const name of ['s', 't', 'ch', 'd', 'b', 'dt', 'e', 'st', 'bt', 'vb', 'y', 'f']) {
      expect(got(name), name).toEqual(VALUES[name]);
    }
    expect(JSON.parse(got('j') as string)).toEqual(JSON.parse(VALUES.j as string));
    expect(got('id')).toBe(id);
  });
});

describe('Gerar UPDATE da célula', () => {
  it('rewrites every kind of value as it is, and the selected literal can be typed over with an expression', async () => {
    const id = '4611686018427387905';
    await admin.query('DELETE FROM grid_kinds WHERE id = ?', [id]);
    await admin.query('INSERT INTO grid_kinds (id, s) VALUES (?, ?)', [id, 'old']);
    const s = await open();
    const read = `SELECT * FROM grid_kinds WHERE id = ${id}`;
    const seed = await exec(s, read);
    const target = gridEditability(seed, await schema(), dialect.valueKind) as EditTarget;
    expect(target.editable).toBe(true);
    const names = seed.columns!.map((c) => c.name);
    const cells: PendingCells = { 0: {} };
    for (const [name, value] of Object.entries(VALUES)) cells[0]![names.indexOf(name)] = value;
    const [update] = buildGridUpdates(dialect, target, seed.rows!, cells);
    expect((await s.execute(update!.sql, { maxRows: 1 })).error).toBeUndefined();

    // the row as the server holds it now: NULLs and every typed value of VALUES
    const before = await exec(s, read);
    for (const name of names.filter((n) => n !== 'id')) {
      const column = names.indexOf(name);
      const value = before.rows![0]![column] ?? null;
      const { text } = buildCellUpdates(dialect, target, before.rows!, column, [{ row: 0, value }]);
      const done = await s.execute(text.slice(0, -1), { maxRows: 1 });
      expect(done.error, name).toBeUndefined();
      expect(done.affectedRows, name).toBe(1);
    }
    const after = await exec(s, read);
    expect(after.rows![0]!.map((v) => (typeof v === 'object' && v !== null ? v : v === null ? null : String(v)))).toEqual(
      before.rows![0]!.map((v) => (typeof v === 'object' && v !== null ? v : v === null ? null : String(v))),
    );

    // typing over the selected literal: the statement is still one UPDATE by the key and the server evaluates it
    const sCol = names.indexOf('s');
    const { text, ranges } = buildCellUpdates(dialect, target, before.rows!, sCol, [{ row: 0, value: before.rows![0]![sCol] ?? null }]);
    const typed = text.slice(0, ranges[0]!.from) + "CONCAT('a', UPPER('b'))" + text.slice(ranges[0]!.to, -1);
    expect(dialect.splitStatements(typed + ';')).toHaveLength(1);
    expect((await s.execute(typed, { maxRows: 1 })).affectedRows).toBe(1);
    const last = await exec(s, `SELECT s FROM grid_kinds WHERE id = ${id}`);
    expect(last.rows![0]![0]).toBe('aB');
  });
});

describe('Aplicar through the SessionManager', () => {
  const env: Environment = { id: 'e', projectId: 'p', name: 'dev', engine: 'mysql', host: '', port: 0, credentialId: 'c', production: false };
  const lines: PersonTrailLine[] = [];
  let manager: SessionManager;

  beforeAll(() => {
    const f = fixture();
    manager = new SessionManager({
      getEnvironment: (id) => (id === 'e' ? { ...env, host: f.host, port: f.port } : undefined),
      resolveConnectParams: async () => params(),
      getDriver: () => mysqlDriver,
      getDialect,
      emit: () => undefined,
      now: () => Date.now(),
      trail: { append: (l) => lines.push(l) },
    });
  });
  afterAll(() => manager.closeAll());

  it('in Transação: found rows count, the trail label, and Rollback undoes it', async () => {
    await manager.open('tx', 'e');
    await manager.setMode('tx', 'transaction');
    const sql = "UPDATE `" + fixture().database + "`.`grid_people` SET `name` = 'Ana' WHERE `id` = 1;\nUPDATE `" + fixture().database + "`.`grid_people` SET `name` = 'X' WHERE `id` = 999;";
    const res = await manager.run('tx', { sql, scope: 'all', cursor: 0, maxRows: 1, origin: 'grid' });
    // the same value still counts as found (FOUND_ROWS); a gone row finds 0
    expect(res.results.map((r) => r.affectedRows)).toEqual([1, 0]);
    expect(res.session.transaction.open).toBe(true);
    expect(lines.filter((l) => l.event === 'statement' && l.state === 'ok').map((l) => l.detail)).toEqual(['Edição na grade', 'Edição na grade']);
    await manager.rollback('tx');
    await manager.close('tx');
  });
});
